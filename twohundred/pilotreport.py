"""Offline: grade every finished run under results/phase2/<pilot|runs> and write a summary.

    python -m twohundred.pilotreport [pilot|runs]

Writes grades.json and summary.md next to the runs. `total_cost_usd` is what Claude Code
reports; on a subscription token it is notional, not money spent (decision 29).
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

from .config import RESULTS, load_settings
from .oracles import grade
from .rundir import write_scrubbed


def _skill_loaded(meta: dict) -> bool | None:
    if meta.get("agent_cli") == "codex":
        return (meta.get("agent") or {}).get("skill_read")
    skills = (meta.get("agent") or {}).get("skills")
    return None if skills is None else "assemblyai" in skills


def _mcp(meta: dict) -> str:
    if meta.get("agent_cli") == "codex":
        return f"calls:{(meta.get('agent') or {}).get('mcp_calls')}" if meta.get("mcp_url") else "-"
    servers = (meta.get("agent") or {}).get("mcp_servers") or []
    return ", ".join(f"{s.get('name')}:{s.get('status')}" for s in servers if isinstance(s, dict)) or "-"


API_HOST = re.compile(r"^(api|streaming|sync|dictation|tts(\.us|\.eu)?|llm-gateway|cdn)\.(eu\.)?assemblyai\.com$|"
                      r"^(pypi\.org|files\.pythonhosted\.org|registry\.npmjs\.org|deb\.nodesource\.com|"
                      r"host\.docker\.internal|localhost|127\.0\.0\.1)$")


def outside_fetches(run_dir: Path) -> list[str]:
    """Shell commands that name a URL on a host that is not an API, a package index or local (decision 30)."""
    hits = []
    for line in (run_dir / "agent.jsonl").read_text(encoding="utf-8").splitlines():
        m = json.loads(line)["msg"]
        item = m.get("item") if isinstance(m.get("item"), dict) else {}
        if m.get("type") == "item.completed" and item.get("type") == "command_execution":
            for host in re.findall(r"https?://([A-Za-z0-9.\-]+)", str(item.get("command") or "")):
                if not API_HOST.match(host.lower()):
                    hits.append(host.lower())
            continue
        if m.get("type") != "assistant":
            continue
        for c in (m.get("message") or {}).get("content") or []:
            if c.get("type") != "tool_use" or c.get("name") != "Bash":
                continue
            cmd = str((c.get("input") or {}).get("command") or "")
            for host in re.findall(r"https?://([A-Za-z0-9.\-]+)", cmd):
                if not API_HOST.match(host.lower()):
                    hits.append(host.lower())
    return sorted(set(hits))


def main(kind: str = "pilot") -> int:
    root = RESULTS / "phase2" / kind
    rows = []
    for meta_path in sorted(root.glob("*/*/*/meta.json")):
        d = meta_path.parent
        meta = json.loads(meta_path.read_text(encoding="utf-8"))
        if not meta.get("complete"):
            continue
        g = grade(meta["task"], d)
        ag = meta.get("agent") or {}
        rows.append({"task": meta["task"], "condition": meta["condition"], "index": meta["index"],
                     "runs": g["runs"], "outcome": g["outcome"], "silent_failure": g["silent_failure"],
                     "failed_checks": [k for k, c in g["checks"].items() if not c["pass"]],
                     "runs_problems": g["runs_problems"], "num_turns": ag.get("num_turns"),
                     "subtype": ag.get("subtype"), "cap_hit": ag.get("cap_hit"), "agent_seconds": ag.get("seconds"),
                     "reported_cost_usd": ag.get("total_cost_usd"), "skill_loaded": _skill_loaded(meta),
                     "mcp": _mcp(meta), "outside_fetches": outside_fetches(d),
                     "info": g.get("info"), "secondary": g.get("secondary")})
    write_scrubbed(root / "grades.json", rows, load_settings(require_key=False))
    lines = [f"# Phase 2 {kind}: per-run grades", "",
             "Generated by `python -m twohundred.pilotreport`. Cost is what Claude Code reports; on the owner's "
             "subscription it is notional (decision 29).", "",
             "| Task | Condition | runs | outcome | silent | failed checks | turns | stop | agent s | skill loaded | MCP | non-API URLs |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in sorted(rows, key=lambda r: (r["task"], r["condition"], r["index"])):
        lines.append(f"| {r['task']} | {r['condition']} | {r['runs']} | {r['outcome']} | {r['silent_failure']} | "
                     f"{', '.join(r['failed_checks'] + r['runs_problems']) or '-'} | {r['num_turns']} | "
                     f"{r['subtype']} | {r['agent_seconds']} | {r['skill_loaded']} | {r['mcp']} | "
                     f"{', '.join(r['outside_fetches']) or '-'} |")
    n = len(rows)
    lines += ["", f"{n} runs. runs true: {sum(r['runs'] for r in rows)}. outcome true: {sum(r['outcome'] for r in rows)}. "
              f"silent failures: {sum(r['silent_failure'] for r in rows)}.", ""]
    (root / "summary.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(*(sys.argv[1:2] or ["pilot"])))
